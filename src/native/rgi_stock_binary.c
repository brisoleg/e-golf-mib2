#include <string.h>
#include "sha256.h"
#include "rgi_stock_binary.h"

int rgi_stock_binary_matches(const char *path) {
    static const unsigned char expected[32]={
        0xde,0x99,0xa7,0xf4,0xdd,0x94,0x15,0x89,
        0xc6,0xd5,0x17,0x3b,0x76,0x01,0x85,0x62,
        0x75,0xc4,0xea,0x61,0x52,0x29,0x05,0x8e,
        0xc8,0x4b,0x8e,0x3e,0xfa,0x74,0x8d,0x27
    };
    unsigned char actual[32];
    return path&&rgi_sha256_file(path,actual)==0&&
           memcmp(actual,expected,32)==0;
}
